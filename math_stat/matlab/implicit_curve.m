% T(z) = z^3

figure
f1 = @(x,y) abs((x+i*y).^3 -1)-1; ...
fimplicit(f1,'b'); ...
xlabel('x'), ylabel('y'), grid on, axis equal, ...
title("|z^3-1|-1 = 0");
print("implicit_curve_f1","-dpng");

% T(z) = (Z^3+1)/Z

figure
f2 = @(x,y) abs(((x+i*y).^3+1)./(x+i*y)) - 3*2^(-2/3); ...
fimplicit(f2,'b'); ...
xlabel('x'), ylabel('y'), grid on, axis equal, ...
title("|(z^3+1)/Z|- 3*2^{-2/3} = 0");
print("implicit_curve_f2","-dpng");
