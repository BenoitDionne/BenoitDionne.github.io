% Tree from an IFS with condensation
function rc = cond(x,M)
    ro = [];
    co = [];
    X = [0.5,0.5;0,0.5];
    X1 = round(M*X(:,1));
    for i = 2:size(X,2)
        X2 = round(M*X(:,i));
        R = max(abs(X1(1,1)-X2(1,1)),abs(X1(2,1)-X2(2,1)))+1;
        ro = [ro,round(linspace(X1(1,1),X2(1,1),R))];
        co = [co,round(linspace(X1(2,1),X2(2,1),R))];
        X1 = X2;
    end
    rc = unique([ro;co]','rows')';
end
